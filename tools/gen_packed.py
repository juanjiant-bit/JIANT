"""(V10.7.44) the main loop's texts kept packed in the image (gz.h: one LZB block each, tools/lzb.py, unpacked when
asked): HELP's lines (ui_draw.c HELP_TEXT, 643 B in ~340). Read from the source's #define (its string literals, one
after the other), so the text is edited where it is used; ui_draw.c checks the size against it (a stale header fails).
  gen_packed.py UI_DRAW.C OUT.h"""
import ast
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import lzb  # noqa: E402


def literal(src, name):
    """the bytes of #define name's string literals (backslash-continued lines), with the literal's closing 0"""
    m = re.search(r"^#define " + name + r"\b((?:.*\\\n)*.*)$", src, re.M)
    if not m:
        raise SystemExit(f"gen_packed: no #define {name}")
    body = re.sub(r"/\*.*?\*/", "", m.group(1).replace("\\\n", " "), flags=re.S)
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    return b"".join(ast.literal_eval('b"' + p + '"') for p in parts) + b"\0"


def main(ui_draw, out):
    raw = literal(Path(ui_draw).read_text(), "HELP_TEXT")
    z = lzb.pack(raw)
    assert lzb.unpack(z, 0, len(raw))[0] == raw
    rows = [", ".join(str(b) for b in z[i:i + 24]) for i in range(0, len(z), 24)]
    Path(out).write_text("/* generated by tools/gen_packed.py from firmware/src/ui_draw.c HELP_TEXT: do not edit */\n"
                         "#pragma once\n#include <stdint.h>\n#include \"gz.h\"\n"
                         f"#define HELP_NB {len(raw)}u\n"
                         f"/* HELP_TEXT ({len(raw)} B) as one LZB block ({len(z)} B; gz.h gz_get unpacks it) */\n"
                         f"static const uint8_t HELP_Z[{len(z)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
                         "_Static_assert(HELP_NB <= GZ_MAX, \"gz.h: HELP fits the buffer\");\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:3]))
