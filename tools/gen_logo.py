def catmull(p, n):
    out = []
    for i in range(len(p) - 1):
        p0, p1, p2, p3 = p[max(i - 1, 0)], p[i], p[i + 1], p[min(i + 2, len(p) - 1)]
        for k in range(n):
            t = k / n
            out.append(tuple(0.5 * (2 * p1[j] + (p2[j] - p0[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t * t +
                                    (3 * p1[j] - p0[j] - 3 * p2[j] + p3[j]) * t ** 3) for j in (0, 1)))
    out.append(p[-1])
    return out


def main():
    xs = [x for s in STROKES for x, _ in s]
    ys = [y for s in STROKES for _, y in s]
    pad = 8                                             # (the pen's half width, in the drawing's pixels, a margin)
    x0, x1, y0, y1 = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
    sc = min((W - 6) / (x1 - x0), (H - 6) / (y1 - y0))
    ox, oy = (W - (x1 - x0) * sc) / 2, (H - (y1 - y0) * sc) / 2
    data, n, prev = [], 0, []
    for s in STROKES:
        c = [((x - x0) * sc + ox, (y - y0) * sc + oy) for x, y in catmull(s, 12)]
        pts, acc = [c[0]], 0.0
        for a, b in zip(c, c[1:]):
            acc += math.dist(a, b)
            if acc >= STEP:
                pts.append(b)
                acc = 0.0
        if pts[-1] != c[-1]:
            pts.append(c[-1])
        q = []
        for x, y in pts:
            p = (int(round(x)), int(round(y)))
            if not q or p != q[-1]:
                q.append(p)
        for i, (x, y) in enumerate(q):
            data += [x, y | (128 if i == 0 else 0)]
            n += 1
        prev.append(q)
    lines = ["/* generated by tools/gen_logo.py from assets/ui-art/signature/jiant-fm-logo.jpg: the power-on logo */",
             "#pragma once", f"#define SIG_W {W}", f"#define SIG_H {H}", f"#define SIG_N {n}",
             "static const uint8_t SIG_PTS[SIG_N * 2] = {"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
    lines.append("};")
    open(sys.argv[1], "w").write("\n".join(lines) + "\n")
    print(f"{len(STROKES)} strokes, {n} points, {len(data)} bytes")
    if "--png" in sys.argv:
        from PIL import Image, ImageDraw
        z = 4
        pv = Image.new("RGB", (240 * z, (H + 12) * z))
        d = ImageDraw.Draw(pv)
        X0 = (240 - W) // 2
        for q in prev:
            for x, y in q:
                f = x / W
                st = [(255, 80, 90), (255, 0, 230), (140, 0, 240), (40, 0, 255)]
                k = min(int(f * 3), 2); u = f * 3 - k
                col = tuple(int(st[k][j] + (st[k + 1][j] - st[k][j]) * u) for j in range(3))
                d.ellipse([((X0 + x - 3) * z, (y + 6 - 3) * z), ((X0 + x + 3) * z, (y + 6 + 3) * z)], fill=col)
        pv.save(sys.argv[sys.argv.index("--png") + 1])


if __name__ == "__main__":
    main()
