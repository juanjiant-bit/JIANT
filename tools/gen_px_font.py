EXTRA = {
    0x7C: ["..#..", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],   # |
    0xB7: [".....", ".....", ".....", "..#..", ".....", ".....", "....."],   # the middle dot
    0x85: [".....", ".....", ".....", ".....", ".....", ".....", "#.#.#"],   # the ellipsis
}


def glyph(rows):
    """(bx, by, bw, bh, bytes) of a glyph's ink box, rows top down (row 0 = the capitals' top)"""
    ink = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == '#']
    if not ink:
        return 0, 0, 0, 0, b""
    x0, x1 = min(p[0] for p in ink), max(p[0] for p in ink)
    y0, y1 = min(p[1] for p in ink), max(p[1] for p in ink)
    bits = [1 if rows[y][x] == '#' else 0 for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]
    data = bytearray()
    for i in range(0, len(bits), 8):
        b = 0
        for k, v in enumerate(bits[i:i + 8]):
            b |= v << (7 - k)
        data.append(b)
    return x0, y0 + CAP_Y, x1 - x0 + 1, y1 - y0 + 1, bytes(data)


def main():
    out = Path(sys.argv[1])
    codes = list(range(0x20, 0x7B))
    ex = sorted(EXTRA)
    tab, data = [], bytearray()
    for c in codes + ex:
        rows = G[chr(c)] if c < 0x7B else EXTRA[c]
        for r in rows:
            assert len(r) == 5, (chr(c), r)
        bx, by, bw, bh, d = glyph(rows)
        tab.append((len(data), PITCH * 16, bx, by, bw, bh))
        data += d
    data += b"\0\0"
    hb = [r for r in G['H']]
    assert glyph(hb)[1] == CAP_Y and glyph(hb)[3] == 7
    lines = ["/* generated by tools/gen_px_font.py: AF_X, the 5 x 7 mono pixel face (1 bit a pixel) */",
             f"static const uint8_t AF_X_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    gtext, gsize = ar.glyph_tables("X", tab, 1)     # (0.9.0: packed, as the other faces')
    lines.append(gtext)
    lines.append(f"static const uint8_t AF_X_EX[{len(ex)}] = {{{', '.join(str(c) for c in ex)}}};")
    lines.append(f"static const aafont_t AF_X = {{{H}, {ASC}, 32, 122, {len(ex)}, 0, AF_X_GH, AF_X_GP, AF_X_DATA, 0, 0, AF_X_EX, 0, 0, 1}};")
    lines.append(f"#define AF_X_CAP_Y {CAP_Y}   /* the ink of H: rows {CAP_Y} .. {CAP_Y + 6} of the line */")
    lines.append("#define AF_X_CAP_H 7")
    lines.append(f"#define AF_X_PITCH {PITCH}")
    out.write_text("\n".join(lines) + "\n")
    size = len(data) + gsize + len(ex)
    print(f"face X: 5x7 pixel mono, {len(tab)} glyphs, data {len(data)} B + table {gsize} B = {size} B -> {out}")


if __name__ == "__main__":
    main()
