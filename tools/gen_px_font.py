"""(0.8.5) The UI's smallest face, AF_X: a crisp 5 x 7 mono pixel font (run by tools/build.py generate()).

  gen_px_font.py OUT.h

The approved LENTE mock-up sets its card labels, level tabs, breadcrumb and chips in ~8 px mono capitals; the
antialiased faces start at S (12 px, capitals 9 px tall). AF_X is a 5 x 7 cell on a 6 px pitch (capitals 7 px), the
classic character-LCD shapes, one bit a pixel: no ramp, no phases, no kerning. Capitals, figures and punctuation
and lower case (0x20 .. 0x7A: the units' "ms", "Hz", "dB" as the mock-up writes them), '|', the middle dot (0xB7) and
the ellipsis (0x85).
A glyph is trimmed to its ink box and packed MSB first, a byte boundary per glyph; gfx.c text_run draws it with
cv_bits (aafont_t.bits = 1). The same aafont_t as the other faces, so text_w, cv_text_in, text_fit and the host lint
work unchanged. Line 9 px: the capitals rows 1 .. 7, a descender row 8 (, ; g j p q y).
"""
