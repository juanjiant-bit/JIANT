static void menu_input(uint32_t oct)                  /* oct: ui_input.c oct_taps */
{
    int32_t s;
    uint32_t k, up = (oct >> 1) & 1u, dn = oct & 1u;
    if (ui.menu == 3) {                                /* (V10.14) PROX's page (only opened with the radio running) */
        if (bt_up == BT_RUN) {
            bt_prox_input(up, dn);
            bt_cal_tick();
        } else
            ui.menu = 1;
        enc_drop();
        return;
    }
    if (ui.menu == 2) {                                /* ABOUT: SELECT scrolls (bounded), OCT- back to the tabs */
        if (dn)
            ui.menu = 1, ui.force = 1;
        else if ((s = panel_enc(EN_SELECT)) != 0)
            ui.menu_scroll = (uint16_t)clamp((int32_t)ui.menu_scroll + clamp(s, -128, 128) * 18, 0, menu_scroll_max());
        enc_drop();
        return;
    }
    if ((s = panel_enc(EN_SELECT)) != 0)                /* (0.9.2) SELECT: every row, one a detent */
        ui.menu_sel = (uint8_t)clamp((int32_t)ui.menu_sel + s, 0, MI_COUNT - 1);
    ui.mlv = 1;                                         /* (the tab's rows) */
    if ((s = panel_enc(EN_ALGO)) != 0)
        menu_tab_go(s);
    for (s = 0, k = 0; k < 4u; k++) {                  /* (V10.27, a tester) KNOB k its card's row, as the cards and the */
        int32_t sk = panel_enc(EN_K1 + k);              /* rows' numbers show (was: any knob the selected row) */
        uint32_t t = menu_tab(), r = mtab_first(t) + menu_set() * 4u + k;
        if (!sk) continue;
        if (r < mtab_first(t) + mtab_rows(t) && r < MI_VALUES) {
            ui.menu_sel = (uint8_t)r;
            menu_put(r, menu_step(r, sk));
            ui.force = 1;
        }
    }
    if (ui.menu_sel == MI_BT && up && bt_prox_ok()) {  /* (V10.14) BLUETOOTH ON: OCT+ opens PROX's page */
        ui.menu = 3;
        ui.force = 1;
    } else if (ui.menu_sel < MI_VALUES) {
        /* a step (OCT+ the next value, OCT- the previous); COLOR previews the palette, STYLE is drawn so from the next
         * frame (FX LATCH: the latched effects are off while the menu is up) */
        s += (int32_t)up - (int32_t)dn;
        if (s)
            menu_put(ui.menu_sel, menu_step(ui.menu_sel, s));
    } else if (up) {
        if (ui.menu_sel == MI_PANEL) {
            panel_setup();
            scrn.idle = fm1_ms;                         /* (SCREEN OFF: its own loop had the input) */
            ui.force = 1;
        } else if (ui.menu_sel == MI_INIT) {           /* (0.6.58) INIT SYSTEM: a new song from zero (as SAVE > TOOLS 5,
                                                         * its dialog; UNDO brings the music back) */
            ui.menu = 0;
            confirm_open(CF_INIT_SYS, song.sel);
            ui.force = 1;
        } else {                                       /* MI_ABOUT */
            ui.menu = 2;
            ui.menu_scroll = 0;
            ui.force = 1;
        }
    }
    enc_drop();                                        /* swallow the rest while the menu is up */
}


