/* Generation proves acyclic pairs, depth <=12 and the document size. */
static char *about_byte(char *d,char *end,uint32_t c)
{
    if(c<128u) {if(d<end) *d++=(char)c;}
    else {d=about_byte(d,end,ABOUT_PAIRS[c-128u][0]);d=about_byte(d,end,ABOUT_PAIRS[c-128u][1]);}
    return d;
}

static int32_t menu_text(const char *s, int32_t y, uint16_t col, int draw)
{
    while (*s) {
        char line[64];
        uint32_t n = 0, space = 0, take, prev = 0;
        int32_t pen = 0;                                 /* 1/16 px, as text_w adds it up */
        while (s[n] && n < sizeof line - 1u) {
            uint32_t c = (uint8_t)s[n];
            line[n] = s[n];
            line[n + 1u] = 0;
            pen += (prev ? kern(&AF_S, prev, c) : 0) + font_advance(&AF_S,glyph(&AF_S,c));
            prev = c;
            if (pen >= 227 * 16 - 8)                     /* (pen + 8) >> 4 > 226; (0.9.9-snd4) 2 phases of S made this
                                                            function 2 B longer and its hole before the sound has none */
                break;
            if (s[n] == ' ')
                space = n;
            n++;
        }
        take = s[n] && space ? space : n;
        if (!take) take = 1;                         /* progress even for an unusually wide glyph */
        line[take] = 0;
        if (draw && y + AF_S.h > 0 && y < MENU_DOC_H)
            cv_text(6, y, &AF_S, line, col);
        y += 18;
        s += take;
        while (*s == ' ') s++;
    }
    return y;
}

static int32_t menu_lines(const uint8_t *packed, int32_t y, int draw)
{
    char text[ABOUT_MAX],*d=text;
    if (!bt_hw_seg())
        return y;
    uint32_t n=packed[0]|(uint32_t)packed[1]<<8;
    for(uint32_t i=0;i<n;i++) d=about_byte(d,text+sizeof text-1u,packed[2u+i]);
    *d=0;
    const char *s=text;
    for (; *s; s += str_len(s) + 1u) {
        uint32_t k = (uint8_t)*s - 1u, c = k % 3u;
        y = menu_text(s + 1, y + 4 * (int32_t)(k / 3u), c == 1u ? T_THEME : c == 2u ? T_MID : T_TEXT, draw);
    }
    return y;
}

/* MENU > ABOUT: the clock and the rails, the crash since power-on; (p1, main 0.9.12) the last crash kept in the settings
 * (cpu_safe.c) */
static __attribute__((noinline)) int32_t about_cpu(int32_t y, int draw)
{
    char b[40], n[12];
    (void)n;
#if defined(FM1_IRQ_TARGET)
    {   /* (0.9.9-stab) the clock (MENU > SYSTEM > CPU CLOCK, hal/fm1_sys.h fm1_clk_320) and the core supplies' steps
         * as reached, and as the boot loader left them (fm1_rails_boot: V15's 7 / 15 wanted; the boot loader's 3 / 11) */
        static const char RL[4][3] = {"S ", "/", " (", "/"};
        uint32_t i;
        str_cpy(b, fm1_clk_320() ? "CPU 320 MHZ  RAIL" : "CPU 360 MHZ  RAIL", sizeof b);
        for (i = 0; i < 4u; i++) {
            str_cpy(b + str_len(b), RL[i], 4);
            fmt_int(n, fm1_rails[(i + 2u) & 3u]);
            str_cpy(b + str_len(b), n, 4);
        }
        str_cpy(b + str_len(b), fm1_power_ready ? ") DC" : ")", 5);   /* (V10.11) DC: the stock supply setup took */
        y = menu_text(b, y, T_TEXT, draw);
        if (fm1_crash.magic == FM1_CRASH_MAGIC && fm1_crash.count) {   /* (0.9.9-stab) the last crash since power-on
                                                     * (.noinit, hal/fm1_irq.h): what its red screen showed, in hex */
            static const char *const CL[6] = {"CRASH ", " VEC ", "PC ", " SP ", "C2 ", " BUS "};
            const uint32_t cv[6] = {fm1_crash.count, fm1_crash.vec, fm1_crash.pc, fm1_crash.sp, fm1_crash.other_pc,
                                    fm1_crash.bus[5] | fm1_crash.bus[3]};
            for (i = 0; i < 6u; i++) {
                uint32_t k, v = cv[i];
                if (!(i & 1u))
                    b[0] = 0;
                str_cpy(b + str_len(b), CL[i], 7);
                if (i == 0) {
                    fmt_int(n, (int32_t)v);
                    str_cpy(b + str_len(b), n, 8);
                } else {
                    for (k = str_len(b) + 8u; k > str_len(b); k--, v >>= 4)
                        b[k - 1u] = "0123456789ABCDEF"[v & 15u];
                    b[k + 8u] = 0;
                }
                if (i & 1u)
                    y = menu_text(b, y, T_TEXT, draw);
            }
        }
    }
#endif
    y = menu_text("LAST CRASH", y + 4, T_THEME, draw);   /* (p1, main 0.9.12) kept across power-off (cpu_safe.c) */
    y = menu_text(crash_log_get(b) ? b : "NONE", y, T_TEXT, draw);
    return y;
}
/* (0.6.17) the audio's load since power-on (voice.c load_diag): to tell what happened when it clicked. (V10.13) In the
 * segment (bt.c BTAPP_FN): without it ABOUT goes on with the CPU lines */
